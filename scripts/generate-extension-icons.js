'use strict';

// ── One logo in, five files out ──────────────────────────────────────────────
//
// There used to be three byte-identical copies of the same 501 KB PNG in the
// repo: /logo.png, /extension/icons/logo.png and /electron/extension/icons/
// logo.png. Two of those were committed artifacts of a copy step, and the third
// belonged to a folder that nothing loaded. Worse, that 501 KB file was what the
// manifest handed the browser to draw a 16x16 toolbar icon -- the browser
// downscaled it on every paint, and every extension zip carried half a megabyte
// to do it.
//
// Now /logo.png is the only committed copy and is the only source of truth.
// Everything under extension/icons/ is generated by this script and gitignored.
//
// Outputs:
//   icons/16.png  32.png  48.png  128.png   -> manifest icons + action icons
//   icons/logo.png                          -> the overlay badge drawn by
//                                              content.js and the popup header;
//                                              capped at 256px because nothing
//                                              renders it larger than that.
//
// Run directly, or via `npm run build:extension` / `npm run build`, both of
// which invoke it first. scripts/check-extension-packaging.js knows these files
// are generated and verifies the generator and its source exist rather than
// looking for committed PNGs that a clean clone will never have.

const fs = require('fs');
const fsp = fs.promises;
const path = require('path');
const sharp = require('sharp');

const ROOT = path.resolve(__dirname, '..');
const SOURCE_LOGO = path.join(ROOT, 'logo.png');
const ICON_DIR = path.join(ROOT, 'extension', 'icons');

// Sizes the manifests actually declare. Keep in step with manifest.json and
// manifests/*.json; check-extension-manifests.js asserts they match.
const ICON_SIZES = [16, 32, 48, 128];

// The in-page overlay badge and popup header. 256 is generous for both.
const OVERLAY_MAX = 256;

async function generateIcons() {
  if (!fs.existsSync(SOURCE_LOGO)) {
    throw new Error(
      `Source logo not found at ${SOURCE_LOGO}. This is the only committed ` +
        'copy of the Atlas mark; extension/icons/ is generated from it.',
    );
  }

  await fsp.mkdir(ICON_DIR, { recursive: true });

  for (const size of ICON_SIZES) {
    const target = path.join(ICON_DIR, `${size}.png`);
    await sharp(SOURCE_LOGO)
      // `contain` rather than `cover`: the mark is not square-safe to crop, and
      // a toolbar icon with its edges shaved reads as a rendering bug.
      .resize(size, size, {
        fit: 'contain',
        background: { r: 0, g: 0, b: 0, alpha: 0 },
      })
      .png({ compressionLevel: 9 })
      .toFile(target);
    console.log(`[extension-icons] ${path.relative(ROOT, target)}`);
  }

  const overlayTarget = path.join(ICON_DIR, 'logo.png');
  await sharp(SOURCE_LOGO)
    .resize(OVERLAY_MAX, OVERLAY_MAX, {
      fit: 'contain',
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png({ compressionLevel: 9 })
    .toFile(overlayTarget);
  console.log(`[extension-icons] ${path.relative(ROOT, overlayTarget)}`);
}

if (require.main === module) {
  generateIcons()
    .then(() => console.log('[extension-icons] Done.'))
    .catch((err) => {
      console.error('[extension-icons] Failed:', err.message);
      process.exit(1);
    });
}

module.exports = { generateIcons, ICON_SIZES, ICON_DIR, SOURCE_LOGO };
